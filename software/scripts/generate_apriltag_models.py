#!/usr/bin/env python3
"""
Generate Gazebo models of printed AprilTags for perseus_lite_simulation.

    pixi run -e default python software/scripts/generate_apriltag_models.py 0 1 2 3

Writes software/ros_ws/src/perseus_lite_simulation/models/apriltag_<family>_<id>/
(model.config, model.sdf, materials/textures/tag.png). Each model's origin is the tag
centre and its +x axis is the direction the tag FACES, matching the landmark map's
[x, y, z, yaw] convention (perseus_landmarks/config/landmarks*.yaml). The tag face is
size_m (black square) plus a one-cell white border, on a 1 cm grey backing plate.
Add --post for a free-standing tag on a pole down to the ground.
"""

import argparse
import os
import sys

import cv2
import numpy as np

FAMILIES = {
    "16h5": (cv2.aruco.DICT_APRILTAG_16h5, 6),
    "25h9": (cv2.aruco.DICT_APRILTAG_25h9, 7),
    "36h10": (cv2.aruco.DICT_APRILTAG_36h10, 8),
    "36h11": (cv2.aruco.DICT_APRILTAG_36h11, 8),
}

MODEL_SDF = """<?xml version="1.0"?>
<!-- Generated by software/scripts/generate_apriltag_models.py: do not edit by hand. -->
<sdf version="1.8">
  <model name="apriltag_{family}_{tag_id}">
    <static>true</static>
    <link name="link">
      <!-- Backing plate, just behind the face. -->
      <collision name="plate_collision">
        <pose>-0.005 0 0 0 0 0</pose>
        <geometry><box><size>0.01 {face} {face}</size></box></geometry>
      </collision>
      <visual name="plate">
        <pose>-0.005 0 0 0 0 0</pose>
        <geometry><box><size>0.01 {face} {face}</size></box></geometry>
        <material><ambient>0.6 0.6 0.6 1</ambient><diffuse>0.6 0.6 0.6 1</diffuse></material>
      </visual>
      <!-- The printed tag: a plane facing +x. -->
      <visual name="tag">
        <pose>0.0005 0 0 0 0 0</pose>
        <geometry><plane><normal>1 0 0</normal><size>{face} {face}</size></plane></geometry>
        <material>
          <!-- Self-lit from its own texture (emissive_map): black cells stay black and
               white cells white whatever the sun angle. A flat emissive colour instead
               lifted the blacks to grey on a back-lit tag and it stopped decoding. -->
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <emissive>1 1 1 1</emissive>
          <pbr><metal>
            <albedo_map>model://apriltag_{family}_{tag_id}/materials/textures/tag.png</albedo_map>
            <emissive_map>model://apriltag_{family}_{tag_id}/materials/textures/tag.png</emissive_map>
            <roughness>1.0</roughness>
            <metallicity>0.0</metallicity>
          </metal></pbr>
        </material>
      </visual>{post}
    </link>
  </model>
</sdf>
"""

POST = """
      <visual name="post">
        <pose>-0.02 0 {post_z} 0 0 0</pose>
        <geometry><cylinder><radius>0.01</radius><length>{post_len}</length></cylinder></geometry>
        <material><ambient>0.3 0.3 0.3 1</ambient><diffuse>0.3 0.3 0.3 1</diffuse></material>
      </visual>
      <collision name="post_collision">
        <pose>-0.02 0 {post_z} 0 0 0</pose>
        <geometry><cylinder><radius>0.01</radius><length>{post_len}</length></cylinder></geometry>
      </collision>"""

MODEL_CONFIG = """<?xml version="1.0"?>
<model>
  <name>apriltag_{family}_{tag_id}</name>
  <version>1.0</version>
  <sdf version="1.8">model.sdf</sdf>
  <description>AprilTag {family} id {tag_id}, black square {size} m (generated).</description>
</model>
"""


def render(family, tag_id, cell_px):
    """Render the tag with a one-cell white border (as perseus_landmarks::render_tag)."""
    dictionary_id, black_cells = FAMILIES[family]
    dictionary = cv2.aruco.getPredefinedDictionary(dictionary_id)
    marker = cv2.aruco.generateImageMarker(
        dictionary, tag_id, black_cells * cell_px, borderBits=1
    )
    image = np.full(((black_cells + 2) * cell_px,) * 2, 255, np.uint8)
    image[cell_px:-cell_px, cell_px:-cell_px] = marker
    return image, black_cells


def main():
    """Parse arguments and write one model per id."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("ids", type=int, nargs="+")
    parser.add_argument("--family", default="36h11", choices=sorted(FAMILIES))
    parser.add_argument(
        "--size", type=float, default=0.16, help="black square edge, metres"
    )
    parser.add_argument(
        "--post",
        type=float,
        default=0.0,
        help="height of the tag centre above the ground, for a pole",
    )
    parser.add_argument(
        "--flip",
        action="store_true",
        help="mirror the texture (if a renderer maps it mirrored)",
    )
    parser.add_argument(
        "--out",
        default=os.path.join(
            os.path.dirname(os.path.abspath(__file__)),
            "..",
            "ros_ws",
            "src",
            "perseus_lite_simulation",
            "models",
        ),
    )
    args = parser.parse_args()
    for tag_id in args.ids:
        image, black_cells = render(args.family, tag_id, 40)
        if args.flip:
            image = np.fliplr(image)
        face = args.size * (black_cells + 2) / black_cells
        name = f"apriltag_{args.family}_{tag_id}"
        textures = os.path.join(args.out, name, "materials", "textures")
        os.makedirs(textures, exist_ok=True)
        cv2.imwrite(os.path.join(textures, "tag.png"), image)
        post = ""
        if args.post > face / 2:
            length = args.post - face / 2
            post = POST.format(
                post_z=f"{-(face / 2 + length / 2):.4f}", post_len=f"{length:.4f}"
            )
        with open(
            os.path.join(args.out, name, "model.sdf"), "w", encoding="utf-8"
        ) as handle:
            handle.write(
                MODEL_SDF.format(
                    family=args.family, tag_id=tag_id, face=f"{face:.4f}", post=post
                )
            )
        with open(
            os.path.join(args.out, name, "model.config"), "w", encoding="utf-8"
        ) as handle:
            handle.write(
                MODEL_CONFIG.format(family=args.family, tag_id=tag_id, size=args.size)
            )
        print(f"wrote {name} (face {face:.3f} m)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
